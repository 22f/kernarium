"""dependencies/andarium-accessibility/pin-archives.py makes no network call
of its own.

Its online builds and repository lookups run only as the child of
prepare.sh --pin-archives; run any other way the tool refuses before it reads
a file or opens a connection. `compare` and the list and metadata parsing
need no network, and the builds it starts are the phone releases only, in
repositories on the three hosts the pin run may contact.
"""

from __future__ import annotations

__import__("sys").dont_write_bytecode = True

import importlib.util
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[3]
TOOL = ROOT / "dependencies/andarium-accessibility/pin-archives.py"
specification = importlib.util.spec_from_file_location("pin_archives", TOOL)
pin_archives = importlib.util.module_from_spec(specification)
sys.modules[specification.name] = pin_archives
specification.loader.exec_module(pin_archives)

DIGEST_A = "a" * 64
DIGEST_B = "b" * 64
METADATA = """<?xml version="1.0" encoding="UTF-8"?>
<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">
  <components>
    <component group="androidx.core" name="core" version="1.0.0">
      <artifact name="core-1.0.0.aar"><sha256 value="%s" origin="Generated by Gradle"/></artifact>
    </component>
  </components>
</verification-metadata>
""" % DIGEST_A


def run(*arguments: str, environment: dict | None = None) -> subprocess.CompletedProcess:
    base = {key: value for key, value in os.environ.items() if key != pin_archives.PARENT_ENV}
    return subprocess.run(
        [sys.executable, "-B", str(TOOL), *arguments], env={**base, **(environment or {})},
        stdin=subprocess.DEVNULL, capture_output=True, text=True,
    )


class PinArchivesTests(unittest.TestCase):
    def setUp(self) -> None:
        self.directory = tempfile.TemporaryDirectory()
        self.root = Path(self.directory.name)

    def tearDown(self) -> None:
        self.directory.cleanup()

    def write(self, name: str, text: str) -> Path:
        path = self.root / name
        path.write_text(text, encoding="utf-8")
        return path

    def test_run_directly_it_refuses_before_it_reads_anything(self) -> None:
        for arguments in (
            ("metadata", "--metadata", str(self.root / "absent.xml"), "--output", str(self.root / "out.tsv")),
            ("pin", "--sources", "s", "--cache", "c", "--archives", "a", "--work", "w", "--java-home", "j",
             "--android-home", "h", "--output", str(self.root / "out.tsv")),
        ):
            result = run(*arguments)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("only dependencies/prepare.sh may do", result.stderr)
            self.assertFalse((self.root / "out.tsv").exists())

    def test_a_process_ID_that_is_not_the_parent_does_not_unlock_it(self) -> None:
        for value in ("1", "not-a-number", ""):
            result = run("metadata", "--metadata", str(self.root / "absent.xml"), "--output",
                         str(self.root / "out.tsv"), environment={pin_archives.PARENT_ENV: value})
            self.assertIn("only dependencies/prepare.sh may do", result.stderr, value)

    def test_every_network_function_refuses_first(self) -> None:
        def reached(*_a, **_k):
            raise AssertionError("the network was reached")

        with mock.patch.object(pin_archives.urllib.request, "urlopen", reached), \
                mock.patch.object(pin_archives.subprocess, "run", reached), \
                mock.patch.object(pin_archives.subprocess, "Popen", reached), \
                mock.patch.dict(os.environ, {}, clear=False):
            os.environ.pop(pin_archives.PARENT_ENV, None)
            calls = (
                lambda: pin_archives.serves("https://repo.maven.apache.org/maven2/x", DIGEST_A),
                lambda: pin_archives.module_file("https://repo.maven.apache.org/maven2/x.module"),
                lambda: pin_archives.locate(("g", "m", "1", "m-1.jar", DIGEST_A)),
                lambda: pin_archives.pin({("g", "m", "1", "m-1.jar", DIGEST_A)}, []),
                lambda: pin_archives.online_metadata(
                    ROOT, self.root, self.root, self.root, self.root, self.root, self.root),
            )
            for call in calls:
                with self.assertRaises(SystemExit) as raised:
                    call()
                self.assertIn("only dependencies/prepare.sh may do", str(raised.exception))

    def test_only_the_functions_that_refuse_first_open_a_connection_or_a_build(self) -> None:
        source = TOOL.read_text(encoding="utf-8")
        for needle in ("urlopen(", "subprocess.run(", "subprocess.Popen("):
            for number, line in enumerate(source.splitlines(), 1):
                if needle in line and not line.lstrip().startswith(("#", '"')):
                    function = max(
                        (index for index, text in enumerate(source.splitlines()[:number]) if text.startswith("def ")))
                    body = "\n".join(source.splitlines()[function:number])
                    self.assertIn("require_prepare()", body, f"line {number} uses {needle} without refusing first")

    def test_compare_needs_no_network_and_names_a_digest_that_moved(self) -> None:
        old = self.write("old.tsv", "name\turl\tsha256\nx.zip\thttps://h/x.zip\t%s\ny.aar\thttps://h/y.aar\t%s\n" % (DIGEST_A, DIGEST_A))
        new = self.write("new.tsv", "name\turl\tsha256\nx.zip\thttps://h/x.zip\t%s\ny.aar\thttps://h/y.aar\t%s\nz.aar\thttps://h/z.aar\t%s\n"
                         % (DIGEST_A, DIGEST_B, DIGEST_B))
        result = run("compare", str(old), str(new))
        self.assertEqual(result.returncode, 1)
        self.assertIn(f"DIFFERS\ty.aar\t{DIGEST_A}\t{DIGEST_B}", result.stdout)
        self.assertIn("new\tz.aar", result.stdout)
        self.assertIn("1 rows keep their digest", result.stderr)
        same = run("compare", str(old), str(old))
        self.assertEqual(same.returncode, 0)
        self.assertEqual(same.stdout.strip(), "")

    def test_a_removed_row_is_reported_and_is_not_a_changed_digest(self) -> None:
        old = self.write("old.tsv", "name\turl\tsha256\nx.zip\thttps://h/x.zip\t%s\ngone.aar\thttps://h/g\t%s\n" % (DIGEST_A, DIGEST_B))
        new = self.write("new.tsv", "name\turl\tsha256\nx.zip\thttps://h/x.zip\t%s\n" % DIGEST_A)
        result = run("compare", str(old), str(new))
        self.assertEqual(result.returncode, 0)
        self.assertIn(f"removed\tgone.aar\t{DIGEST_B}", result.stdout)

    def test_metadata_and_archive_names(self) -> None:
        path = self.write("metadata.xml", METADATA)
        self.assertEqual(pin_archives.artifacts(path), {("androidx.core", "core", "1.0.0", "core-1.0.0.aar", DIGEST_A)})
        self.assertEqual(
            pin_archives.archive_name("https://dl.google.com/dl/android/maven2/androidx/core/core/1.0.0/core-1.0.0.aar"),
            "maven~androidx.core~core~1.0.0~core-1.0.0.aar")
        with self.assertRaises(SystemExit):
            pin_archives.archive_name("https://example.invalid/maven2/a/b/1/b-1.jar")

    def test_the_builds_are_the_phone_releases_only(self) -> None:
        tasks = {name: task for name, _, task, _ in pin_archives.BUILDS}
        self.assertEqual(tasks, {"talkback": "assemblePhoneRelease", "espeak-ng": "assembleRelease"})
        command = pin_archives.gradle_command(
            Path("/g"), Path("/p"), Path("/h"), Path("/i.gradle"), "assemblePhoneRelease", [])
        self.assertEqual(command[-1], "assemblePhoneRelease")
        self.assertIn("--write-verification-metadata", command)
        self.assertNotIn("--offline", command)
        self.assertNotIn("help", command)
        self.assertIn("-Pandroid.builder.sdkDownload=false", command)

    def test_the_online_init_script_allows_three_hosts_and_only_maven_repositories(self) -> None:
        self.assertEqual(sorted(pin_archives.HOSTS), ["dl.google.com", "plugins.gradle.org", "repo.maven.apache.org"])
        script = pin_archives.INIT_SCRIPT % {"hosts": ", ".join(f"'{host}'" for host in pin_archives.HOSTS)}
        for host in pin_archives.HOSTS:
            self.assertIn(f"'{host}'", script)
        self.assertIn("is not a Maven repository", script)
        self.assertIn("location.scheme != 'https'", script)
        self.assertEqual(script.count("check("), 4)


if __name__ == "__main__":
    unittest.main(verbosity=2)
